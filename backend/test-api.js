import { startServer } from './src/server.js';

async function runTests() {
  const server = await startServer();
  const BASE_URL = 'http://localhost:5000';

  async function request(path, options = {}) {
    const url = `${BASE_URL}${path}`;
    const headers = { 'Content-Type': 'application/json', ...(options.headers || {}) };
    const res = await fetch(url, {
      method: options.method || 'GET',
      headers,
      body: options.body ? JSON.stringify(options.body) : undefined,
    });
    const data = await res.json().catch(() => ({}));
    return { status: res.status, data };
  }

  console.log('\n--- STARTING API VERIFICATION TESTS ---');

  // 1. Health check
  const health = await request('/api/health');
  console.log(`1. GET /api/health -> Status: ${health.status}, OK: ${health.data.status === 'ok'}`);

  // 2. GET /posts
  const postsRes = await request('/posts');
  console.log(`2. GET /posts -> Status: ${postsRes.status}, Post count: ${postsRes.data.posts?.length}`);

  // 3. Login as admin
  const loginRes = await request('/auth/login', {
    method: 'POST',
    body: { email: 'admin@miniblog.com', password: 'admin123' },
  });
  console.log(`3. POST /auth/login (Admin) -> Status: ${loginRes.status}, Role: ${loginRes.data.user?.role}`);
  const adminToken = loginRes.data.token;

  // 4. Create post as admin
  const createPostRes = await request('/posts', {
    method: 'POST',
    headers: { Authorization: `Bearer ${adminToken}` },
    body: {
      title: 'Test Post from API Test Suite',
      content: '## Automated Verification\nThis post was generated by the backend test runner.',
      tags: ['testing', 'automation'],
    },
  });
  console.log(`4. POST /posts (Admin) -> Status: ${createPostRes.status}, ID: ${createPostRes.data.post?.id}`);
  const newPostId = createPostRes.data.post?.id;

  // 5. Register a new reader
  const registerRes = await request('/auth/register', {
    method: 'POST',
    body: {
      name: 'Bob Tester',
      email: `bob_${Date.now()}@example.com`,
      password: 'password123',
      role: 'reader',
    },
  });
  console.log(`5. POST /auth/register (Reader) -> Status: ${registerRes.status}, Role: ${registerRes.data.user?.role}`);
  const readerToken = registerRes.data.token;

  // 6. Reader attempts to create post (Should be Forbidden 403)
  const readerPostAttempt = await request('/posts', {
    method: 'POST',
    headers: { Authorization: `Bearer ${readerToken}` },
    body: {
      title: 'Should Fail Post',
      content: 'This should be blocked for non-admin readers.',
    },
  });
  console.log(`6. POST /posts (Reader forbidden check) -> Status: ${readerPostAttempt.status} (Expected 403)`);

  // 7. Reader adds a comment on the new post
  const commentRes = await request(`/posts/${newPostId}/comments`, {
    method: 'POST',
    headers: { Authorization: `Bearer ${readerToken}` },
    body: { text: 'Verified that reader can add comments successfully!' },
  });
  console.log(`7. POST /posts/:id/comments (Reader) -> Status: ${commentRes.status}, Text: ${commentRes.data.comment?.text}`);

  // 8. Public reads comments on that post
  const getCommentsRes = await request(`/posts/${newPostId}/comments`);
  console.log(`8. GET /posts/:id/comments (Public) -> Status: ${getCommentsRes.status}, Count: ${getCommentsRes.data.count}`);

  // 9. Admin updates post
  const updateRes = await request(`/posts/${newPostId}`, {
    method: 'PUT',
    headers: { Authorization: `Bearer ${adminToken}` },
    body: { title: 'Updated Test Post Title' },
  });
  console.log(`9. PUT /posts/:id (Admin) -> Status: ${updateRes.status}, Title: ${updateRes.data.post?.title}`);

  // 10. Admin deletes post
  const deleteRes = await request(`/posts/${newPostId}`, {
    method: 'DELETE',
    headers: { Authorization: `Bearer ${adminToken}` },
  });
  console.log(`10. DELETE /posts/:id (Admin) -> Status: ${deleteRes.status}, Message: ${deleteRes.data.message}`);

  console.log('--- ALL API TESTS COMPLETED SUCCESSFULLY ---\n');
  server.close();
  process.exit(0);
}

runTests().catch((err) => {
  console.error('Test suite failed:', err);
  process.exit(1);
});
